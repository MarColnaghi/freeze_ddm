function model = model_1()
% Refactored model with process types and nested structures

% Process 1: First Component
model.process1 = struct(...
    'type', 'ddm', ... % Drift Diffusion Model
    'mu', struct( ...
        'predictors', {{ struct('name', 'sm', 'bounds', [0, 2.0]) }}, ...
        'link', @(x) x, ...
        'ground_truth', [0] ...
    ), ...
    'theta', struct( ...
        'predictors', {{ struct('name', 'intercept', 'bounds', [0.1, 1.0]) }}, ...
        'link', @(x) x, ...
        'ground_truth', [0] ...
    ) ...
);

% Process 2: Second Component
model.process2 = struct(...
    'type', 'ddm', ... % Exponential Distribution
    'mu', struct( ...
        'predictors', {{ struct('name', 'sm', 'bounds', [0.5, 2.8]) }}, ...
        'link', @(x) x, ...
        'ground_truth', [0] ...
    ), ...
    'theta', struct( ...
        'predictors', {{ ...
            struct('name', 'ls', 'bounds', [0.2, 2]), ...
            struct('name', 'intercept', 'bounds', [1, 3]) ...
        }}, ...
        'link', @(x) x, ...
        'ground_truth', [0 0] ...
    ) ...
);

% Mixture Logic
model.shared = struct( ...
    'pmix', struct( ...
        'predictors', {{ ...
            struct('name', 'fs', 'bounds', [-2, 0]), ...
            struct('name', 'ln', 'bounds', [-2, 2]), ...
            struct('name', 'ls', 'bounds', [-2, 2]) ...
        }}, ...
        'link', @(x) 1./(1 + exp(-x)), ...
        'ground_truth', [0 0 0] ...
    ), ...
    'tndt', struct( ...
        'predictors', {{ ...
            struct('name', 'intercept', 'bounds', [0, 0.55]) ...
        }}, ...
        'link', @(x) x, ...
        'ground_truth', [0] ...
    ) ...
);

end